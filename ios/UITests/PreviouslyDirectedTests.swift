    func testLateSearchCannotOverwriteNewerQuery() async throws {
        let driver = QADriver(test: self, configuration: try QAConfiguration())
        defer { driver.attachEvidence(name: "late-search"); driver.app.terminate() }
        try await driver.begin()
        let before = try await driver.oracle.state("fixture-a")
        try driver.navigate("discover")
        try await driver.oracle.fault("delay", account: "fixture-a", path: "/search", delayMs: 1_500)
        driver.record("fault", "/search", "completed", "First response delayed 1500ms; replacement query is immediate.")
        try driver.replaceText("anime", in: "qa.search.field")
        try await driver.oracle.waitForFault("delay", path: "/search", account: "fixture-a", inFlight: true)
        driver.record("fault-dispatched", "/search", "completed", "Scratch server confirmed the old query is in flight.")
        try driver.replaceText("plan", in: "qa.search.field")
        try driver.require("qa.search.result.qa-plan")
        try await driver.oracle.waitForFault("delay", path: "/search", account: "fixture-a", inFlight: false)
        driver.record("fault-completed", "/search", "completed", "Scratch server confirmed the old response completed.")
        XCTAssertTrue(driver.element("qa.search.result.qa-plan").exists)
        XCTAssertFalse(driver.element("qa.search.result.qa-anime").exists, "An old result replaced the new query.")
        let longQuery = String(repeating: "x", count: 120)
        try driver.replaceText(longQuery, in: "qa.search.field")
        try driver.replaceText(longQuery, in: "qa.search.field")
        try driver.replaceText("QA", in: "qa.search.field")
        try driver.require("qa.search.result.qa-anime")
        driver.record("assert-long-query-replacement", "qa.search.field", "passed", "120 characters entered exactly twice, then explicitly cleared for QA.")
        try driver.dismissKeyboard()
        try driver.navigate("library")
        let after = try await driver.oracle.state("fixture-a")
        XCTAssertEqual(after.progress, before.progress)
        XCTAssertEqual(after.ownership, before.ownership)
    }

    func testCommittedWriteWithLostResponseHasOneEffect() async throws {
        let driver = QADriver(test: self, configuration: try QAConfiguration())
        defer { driver.attachEvidence(name: "lost-response"); driver.app.terminate() }
        try await driver.begin()
        let before = try await driver.oracle.state("fixture-a")
        let initial = try XCTUnwrap(before.episodes(1001))
        try driver.openAnime()
        try await driver.oracle.fault("drop-after-commit", account: "fixture-a")
        driver.record("fault", "/me/progress", "completed", "One response dropped after canonical commit.")
        try driver.markNext()
        try driver.assertProgress(initial + 1)
        let committed = try await driver.oracle.waitForEpisodes(initial + 1, mediaID: 1001, account: "fixture-a")
        XCTAssertEqual(committed.progressCommits, before.progressCommits + 1, "Duplicate logical progress effects are not acceptable.")
        let attempts = try await driver.oracle.waitForRequests(2, method: "PUT", path: "/me/progress", account: "fixture-a")
        _ = try stableStamp(attempts)
        driver.app.terminate()
        try await driver.launch()
        try driver.openAnime()
        try driver.assertProgress(initial + 1)
        let final = try await driver.oracle.state("fixture-a")
        XCTAssertEqual(final.episodes(1001), initial + 1)
        XCTAssertEqual(final.progressCommits, before.progressCommits + 1)
    }

    private func stableStamp(_ requests: [QAOracle.RequestRecord]) throws -> QAOracle.MutationRecord {
        let first = try XCTUnwrap(requests.first?.mutation, "An owned progress write omitted mutation metadata.")
        XCTAssertNotNil(UUID(uuidString: first.operationID))
        XCTAssertNotNil(UUID(uuidString: first.writerID))
        XCTAssertEqual(first.operationID, first.operationID.lowercased())
        XCTAssertEqual(first.writerID, first.writerID.lowercased())
        XCTAssertGreaterThan(first.sequence, 0)
        for request in requests { XCTAssertEqual(request.mutation, first, "One intent changed identity between HTTP attempts.") }
        return first
    }

    func testAccountSwitchDoesNotExposePreviousLibrary() async throws {
        let driver = QADriver(test: self, configuration: try QAConfiguration())
        defer { driver.attachEvidence(name: "account-switch"); driver.app.terminate() }
        try await driver.begin()
        try await driver.oracle.reset("fixture-b")
        try driver.navigate("home")
        try driver.tap("qa.profile.open")
        try driver.tap("qa.signout")
        try driver.tap("qa.signout.confirm")
        try driver.replaceText("fixture-b", in: "qa.signin.dev.field")
        try driver.tap("qa.signin.dev.submit")
        try driver.require("qa.account.fixture-b")
        try driver.navigate("library")
        try driver.require("qa.show.qa-plan")
        XCTAssertFalse(driver.element("qa.show.qa-anime").exists)
        XCTAssertFalse(driver.element("qa.show.qa-tv").exists)
        let a = try await driver.oracle.state("fixture-a")
        let b = try await driver.oracle.state("fixture-b")
        XCTAssertEqual(a.ownership, ["qa-anime", "qa-tv"])
        XCTAssertEqual(b.ownership, ["qa-plan"])
        driver.app.terminate()
        try await driver.launch(account: "fixture-b")
        try driver.require("qa.account.fixture-b")
        try driver.navigate("library")
        try driver.require("qa.show.qa-plan")
        XCTAssertFalse(driver.element("qa.show.qa-anime").exists)
        XCTAssertFalse(driver.element("qa.show.qa-tv").exists)
        driver.record("assert-isolation", "fixture-b", "passed", "A's titles absent before and after B relaunch.")
    }
