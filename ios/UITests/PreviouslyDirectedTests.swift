import XCTest

@MainActor
final class PreviouslyDirectedTests: XCTestCase {
    func testOlderRetryCannotBypassNewerProgressInFlight() async throws {
        let driver = QADriver(test: self, configuration: try QAConfiguration())
        defer { driver.attachEvidence(name: "retry-during-newer-progress"); driver.app.terminate() }
        try await driver.begin()
        let before = try await driver.oracle.state("fixture-a")
        let initial = try XCTUnwrap(before.episodes(1001))
        try driver.openAnime()
        try await driver.oracle.fault("before-commit", account: "fixture-a", remaining: 3)
        try driver.markNext()
        try driver.assertProgress(initial + 1)
        try await driver.oracle.waitForFault("before-commit", path: "/me/progress", account: "fixture-a", inFlight: false, timeout: 10)
        try driver.openProfile()
        try driver.assertValue(String(initial + 1), identifier: "qa.sync.pending.progress.1001")
        try driver.tap("qa.profile.done")

        try driver.openAnime()
        try await driver.oracle.fault("delay", account: "fixture-a", delayMs: 12_000)
        driver.record("fault", "/me/progress", "completed", "Hold newer progress before commit for a controlled 12 seconds.")
        try driver.markNext()
        try driver.assertProgress(initial + 2)
        try await driver.oracle.waitForFault("delay", path: "/me/progress", account: "fixture-a", inFlight: true)
        let held = try await driver.oracle.state("fixture-a")
        XCTAssertEqual(held.episodes(1001), initial)
        try driver.openProfile()
        try driver.assertValue(String(initial + 1), identifier: "qa.sync.pending.progress.1001")
        try await driver.oracle.waitForFault("delay", path: "/me/progress", account: "fixture-a", inFlight: true)
        try driver.tap("qa.sync.retry.progress.1001")
        driver.record("retry-older-in-flight", "qa.sync.retry.progress.1001", "completed", "Actual older Retry tapped while newer server write remained in flight.")
        let final = try await driver.oracle.waitForEpisodes(initial + 2, mediaID: 1001, account: "fixture-a", timeout: 20)
        XCTAssertEqual(final.progressCommits, before.progressCommits + 1, "An obsolete Retry bypassed the lane and committed an intermediate old value.")
        // Leave no delayed request alive to mutate the next case's freshly reset account.
        try await driver.oracle.waitForFault("delay", path: "/me/progress", account: "fixture-a", inFlight: false, timeout: 30)
        let settled = try await driver.oracle.state("fixture-a")
        XCTAssertEqual(settled.episodes(1001), initial + 2)
        XCTAssertEqual(settled.progressCommits, before.progressCommits + 1)
        try driver.assertAbsent("qa.sync.pending.progress.1001")
        try driver.tap("qa.profile.done")
        try driver.openAnime()
        try driver.assertProgress(initial + 2)
    }

    func testAcceptedNewerProgressRetiresOlderFailedRetry() async throws {
        let driver = QADriver(test: self, configuration: try QAConfiguration())
        defer { driver.attachEvidence(name: "obsolete-progress-retry"); driver.app.terminate() }
        try await driver.begin()
        let before = try await driver.oracle.state("fixture-a")
        let initial = try XCTUnwrap(before.episodes(1001))
        try driver.openAnime()
        // APIClient permits two retries: all three attempts fail before any commit.
        try await driver.oracle.fault("before-commit", account: "fixture-a", remaining: 3)
        driver.record("fault", "/me/progress", "completed", "Reject initial write and both automatic retries before commit.")
        try driver.markNext()
        try driver.assertProgress(initial + 1)
        try await driver.oracle.waitForFault("before-commit", path: "/me/progress", account: "fixture-a", inFlight: false, timeout: 10)
        let failed = try await driver.oracle.state("fixture-a")
        XCTAssertEqual(failed.episodes(1001), initial)
        try driver.openProfile()
        try driver.assertValue(String(initial + 1), identifier: "qa.sync.pending.progress.1001")
        try driver.tap("qa.profile.done")

        try driver.openAnime()
        try driver.assertProgress(initial + 1)
        try driver.markNext()
        try driver.assertProgress(initial + 2)
        _ = try await driver.oracle.waitForEpisodes(initial + 2, mediaID: 1001, account: "fixture-a")
        try driver.openProfile()
        try driver.assertAbsent("qa.sync.pending.progress.1001")
        try driver.assertAbsent("qa.sync.retry.progress.1001")
        driver.record("assert-obsolete-retry", "progress.1001", "passed", "Accepted newer value retired the old failed intent.")

        driver.app.terminate()
        try await driver.launch()
        try driver.openAnime()
        try driver.assertProgress(initial + 2)
        let final = try await driver.oracle.state("fixture-a")
        XCTAssertEqual(final.episodes(1001), initial + 2)
        XCTAssertEqual(final.progressCommits, before.progressCommits + 1)
    }

    func testUpdatedFailureRetryUsesNewestIntent() async throws {
        let driver = QADriver(test: self, configuration: try QAConfiguration())
        defer { driver.attachEvidence(name: "latest-failure-retry"); driver.app.terminate() }
        try await driver.begin()
        let before = try await driver.oracle.state("fixture-a")
        let initial = try XCTUnwrap(before.episodes(1001))
        try driver.openAnime()
        for offset in 1...2 {
            try await driver.oracle.fault("before-commit", account: "fixture-a", remaining: 3)
            driver.record("fault", "/me/progress", "completed", "Reject all three attempts for episode \(initial + offset).")
            try driver.markNext()
            try driver.assertProgress(initial + offset)
            try await driver.oracle.waitForFault("before-commit", path: "/me/progress", account: "fixture-a", inFlight: false, timeout: 10)
            try driver.openProfile()
            try driver.assertValue(String(initial + offset), identifier: "qa.sync.pending.progress.1001")
            if offset == 1 {
                try driver.tap("qa.profile.done")
                try driver.openAnime()
                try driver.assertProgress(initial + 1)
            }
        }
        let failed = try await driver.oracle.state("fixture-a")
        XCTAssertEqual(failed.episodes(1001), initial)
        let failedRequests = try await driver.oracle.waitForRequests(6, method: "PUT", path: "/me/progress", account: "fixture-a")
        let older = try stableStamp(Array(failedRequests.prefix(3)))
        let newer = try stableStamp(Array(failedRequests.suffix(3)))
        XCTAssertNotEqual(newer.operationID, older.operationID, "A changed intent reused the old operation ID.")
        XCTAssertEqual(newer.writerID, older.writerID)
        XCTAssertGreaterThan(newer.sequence, older.sequence)
        try driver.tap("qa.sync.retry.progress.1001")
        _ = try await driver.oracle.waitForEpisodes(initial + 2, mediaID: 1001, account: "fixture-a")
        try driver.assertAbsent("qa.sync.pending.progress.1001")
        let retried = try await driver.oracle.state("fixture-a")
        XCTAssertEqual(retried.episodes(1001), initial + 2, "A failure row retained the first write's obsolete retry closure.")
        XCTAssertEqual(retried.progressCommits, before.progressCommits + 1)
        let allRequests = try await driver.oracle.waitForRequests(7, method: "PUT", path: "/me/progress", account: "fixture-a")
        XCTAssertEqual(try stableStamp(Array(allRequests.dropFirst(3))), newer, "Retry minted a different operation for the same pending intent.")
        try driver.tap("qa.profile.done")
        try driver.openAnime()
        try driver.assertProgress(initial + 2)
        driver.record("assert-latest-retry", "progress.1001", "passed", "Updated failure retried the newest value exactly once.")
    }

    func testFailedProgressReplayRetainsMutationIdentityAcrossRelaunch() async throws {
        let driver = QADriver(test: self, configuration: try QAConfiguration())
        defer { driver.attachEvidence(name: "persistent-progress-operation"); driver.app.terminate() }
        try await driver.begin()
        let before = try await driver.oracle.state("fixture-a")
        let initial = try XCTUnwrap(before.episodes(1001))
        try driver.openAnime()
        try await driver.oracle.fault("before-commit", account: "fixture-a", remaining: 3)
        try driver.markNext()
        try await driver.oracle.waitForFault("before-commit", path: "/me/progress", account: "fixture-a", inFlight: false, timeout: 10)
        try driver.openProfile()
        try driver.assertValue(String(initial + 1), identifier: "qa.sync.pending.progress.1001")
        let failed = try await driver.oracle.waitForRequests(3, method: "PUT", path: "/me/progress", account: "fixture-a")
        let operation = try stableStamp(failed)
        driver.app.terminate()
        try await driver.launch()
        try driver.openProfile()
        try driver.assertValue(String(initial + 1), identifier: "qa.sync.pending.progress.1001")
        try driver.tap("qa.sync.retry.progress.1001")
        let final = try await driver.oracle.waitForEpisodes(initial + 1, mediaID: 1001, account: "fixture-a")
        let replayed = try await driver.oracle.waitForRequests(4, method: "PUT", path: "/me/progress", account: "fixture-a")
        XCTAssertEqual(try stableStamp(replayed), operation, "Cold launch minted a second identity for the persisted failed intent.")
        XCTAssertEqual(final.progressCommits, before.progressCommits + 1)
        try driver.tap("qa.profile.done")
        try driver.openAnime()
        try driver.assertProgress(initial + 1)
        driver.record("assert-persistent-operation", "progress.1001", "passed", "Three rejected attempts and the restored Retry action retained the same operation, writer and sequence.")
    }

